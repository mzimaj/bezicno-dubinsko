(function(){
  var STORAGE_LANG = 'bd-lang';

  function getLang(){
    return document.documentElement.getAttribute('lang') === 'en' ? 'en' : 'hr';
  }

  function applyTranslations(lang){
    var dict = window.BD_TRANSLATIONS[lang] || window.BD_TRANSLATIONS.hr;

    document.querySelectorAll('[data-i18n]').forEach(function(el){
      var key = el.getAttribute('data-i18n');
      if (dict[key] !== undefined) el.textContent = dict[key];
    });

    document.querySelectorAll('[data-i18n-html]').forEach(function(el){
      var key = el.getAttribute('data-i18n-html');
      if (dict[key] !== undefined) el.innerHTML = dict[key];
    });

    document.querySelectorAll('[data-i18n-attr]').forEach(function(el){
      var pairs = el.getAttribute('data-i18n-attr').split(',');
      pairs.forEach(function(pair){
        var parts = pair.split(':');
        var attr = parts[0].trim();
        var key = parts[1] ? parts[1].trim() : '';
        if (dict[key] !== undefined) el.setAttribute(attr, dict[key]);
      });
    });

    document.title = dict['meta.title'] || document.title;
    document.documentElement.setAttribute('lang', lang);

    document.querySelectorAll('.lang-toggle button').forEach(function(btn){
      btn.classList.toggle('is-active', btn.getAttribute('data-lang') === lang);
    });
  }

  function setLang(lang){
    try { localStorage.setItem(STORAGE_LANG, lang); } catch(e){}
    applyTranslations(lang);
  }

  document.addEventListener('DOMContentLoaded', function(){
    applyTranslations(getLang());

    var langToggle = document.getElementById('langToggle');
    if (langToggle) {
      langToggle.querySelectorAll('button[data-lang]').forEach(function(btn){
        btn.addEventListener('click', function(){
          setLang(btn.getAttribute('data-lang'));
        });
      });
    }
  });

  window.BD_I18N = { applyTranslations: applyTranslations, getLang: getLang };
})();
